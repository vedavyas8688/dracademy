	<script>
	/* ===== SLIDER WITH PAUSE ON HOVER ===== */
	const EDU_SLIDE_HEIGHT = 380;
	const EDU_INTERVAL = 1200; // slider speed
	const eduIndexes = {};
	const eduTimers = {};

	function eduStart(sliderId) {
		const slider = document.getElementById(sliderId);
		const total = slider.children.length;
		if(eduTimers[sliderId]) return; // don't start multiple intervals
		eduIndexes[sliderId] = eduIndexes[sliderId] || 0;
		eduTimers[sliderId] = setInterval(() => {
			eduIndexes[sliderId] = (eduIndexes[sliderId] + 1) % total;
			slider.style.transform = `translateY(-${eduIndexes[sliderId]*EDU_SLIDE_HEIGHT}px)`;
		}, EDU_INTERVAL);
	}

	function eduStop(sliderId) {
		clearInterval(eduTimers[sliderId]);
		eduTimers[sliderId] = null;
	}

	function eduSwitchTab(sectionIndex, tabIndex) {
		const section = document.querySelectorAll('.edu-section')[sectionIndex];
		const tabs = section.querySelectorAll('.edu-tab');
		const panels = section.querySelectorAll('.edu-tab-panel');
		tabs.forEach(t => t.classList.remove('edu-active'));
		panels.forEach(p => p.classList.remove('edu-active'));
		tabs[tabIndex].classList.add('edu-active');
		panels[tabIndex].classList.add('edu-active');
		const slider = panels[tabIndex].querySelector('.edu-auto-slider');
		if(slider) eduStart(slider.id);
	}
	document.querySelectorAll('.edu-auto-slider').forEach(slider => {
		eduStart(slider.id);
		const wrapper = slider.closest('.edu-slider-wrapper');
		wrapper.addEventListener('mouseenter', () => eduStop(slider.id));
		wrapper.addEventListener('mouseleave', () => eduStart(slider.id));
	});
	/* ===== LIGHTBOX ===== */
	const lightbox = document.getElementById('edu-lightbox');
	const lightboxImg = lightbox.querySelector('img');
	const lightboxClose = document.getElementById('edu-lightbox-close');
	const lightboxPrev = document.getElementById('edu-lightbox-prev');
	const lightboxNext = document.getElementById('edu-lightbox-next');
	let currentImages = [];
	let currentIndex = 0;
	document.querySelectorAll('.edu-tab-panel').forEach(panel => {
		panel.querySelectorAll('.edu-slide a').forEach(link => {
			link.addEventListener('click', e => {
				e.preventDefault();
				currentImages = Array.from(panel.querySelectorAll('.edu-slide a'));
				currentIndex = currentImages.indexOf(link);
				lightboxImg.src = link.href;
				lightbox.style.display = 'flex';
			});
		});
	});

	function showLightbox(index) {
		if(index < 0) index = currentImages.length - 1;
		if(index >= currentImages.length) index = 0;
		currentIndex = index;
		lightboxImg.src = currentImages[currentIndex].href;
	}
	lightboxPrev.addEventListener('click', () => showLightbox(currentIndex - 1));
	lightboxNext.addEventListener('click', () => showLightbox(currentIndex + 1));
	lightboxClose.addEventListener('click', () => lightbox.style.display = 'none');
	lightbox.addEventListener('click', e => {
		if(e.target === lightbox) lightbox.style.display = 'none';
	});
	// ESC + arrow keys
	document.addEventListener('keydown', e => {
		if(e.key === 'Escape' && lightbox.style.display === 'flex') lightbox.style.display = 'none';
		if(e.key === 'ArrowLeft' && lightbox.style.display === 'flex') showLightbox(currentIndex - 1);
		if(e.key === 'ArrowRight' && lightbox.style.display === 'flex') showLightbox(currentIndex + 1);
	});
