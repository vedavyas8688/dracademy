                    <div class="col-12">
                        <div class="dr-empty-state">
                            <h5>No blogs found</h5>
                            <p>Try another date or clear the filter to view all available blogs.</p>
                        </div>
                    </div>
                `;
                return;
            }

            container.innerHTML = blogs.map(blog => `
                <div class="col-12 col-sm-6 col-lg-4 dr-blog-col">
                    <div class="dr-blog-card">
                        <a href="${encodeURI(blog.url)}" class="dr-blog-thumb-wrap" target="_blank" rel="noopener noreferrer">
                            ${buildThumbnail(blog)}
                        </a>

                        <div class="dr-blog-card-body">
                            <div class="dr-blog-meta-row">
                                <div class="dr-blog-date">
                                    ${escapeHtml(formatDate(blog.date))}
                                </div>

                                <div class="dr-blog-stats">
                                    <span class="dr-blog-stat">Views <span class="dr-blog-stat-value">${blog.views}</span></span>
                                    <span class="dr-blog-stat">Likes <span class="dr-blog-stat-value">${blog.likes}</span></span>
                                    <span class="dr-blog-stat">Shares <span class="dr-blog-stat-value">${blog.shares}</span></span>
                                </div>
                            </div>

                            <h3 class="dr-blog-card-title">${escapeHtml(blog.title)}</h3>
                            <p class="dr-blog-card-desc">${escapeHtml(blog.description || generateDescription(blog.title))}</p>
                            <a href="${encodeURI(blog.url)}" class="dr-blog-read-btn" target="_blank" rel="noopener noreferrer">
                                Read More
                            </a>
                        </div>
                    </div>
                </div>
            `).join('');
        }

        function updateCount(blogs) {
            const countEl = document.getElementById('blogCount');
            countEl.textContent = formatCountText(blogs.length);
        }

        function filterBlogsByDate() {
            const dateInput = document.getElementById('dateFilter').value;
            const normalizedSelectedDate = normalizeDateString(dateInput);

            if (!normalizedSelectedDate) {
                filteredBlogs = [...allBlogs];
            } else {
                filteredBlogs = allBlogs.filter(blog => normalizeDateString(blog.date) === normalizedSelectedDate);
            }

            renderBlogGrid(filteredBlogs);
            updateCount(filteredBlogs);
        }

        async function loadBlogs() {
            try {
                const response = await fetch(API_URL, { cache: 'no-store' });

                if (!response.ok) {
                    throw new Error(`HTTP error! Status: ${response.status}`);
                }

                const data = await response.json();

                if (!Array.isArray(data)) {
                    throw new Error('Invalid JSON response format');
                }

                allBlogs = data.map(item => ({
                    title: item.title || 'Untitled Blog',
                    date: normalizeDateString(item.date),
                    url: item.url || '#',
                    description: item.description || '',
                    thumbnail: item.thumbnail || '',
                    views: Number(item.views || 0),
                    likes: Number(item.likes || 0),
                    shares: Number(item.shares || 0)
                }));

                allBlogs = sortBlogsByDateDesc(allBlogs);
                filteredBlogs = [...allBlogs];

                renderBlogGrid(filteredBlogs);
                updateCount(filteredBlogs);

            } catch (error) {
                console.error('Error loading blogs:', error);

                document.getElementById('blogGrid').innerHTML = `
                    <div class="col-12">
                        <div class="dr-empty-state">
                            <h5>Unable to load blogs</h5>
                            <p>Please check fetch.php, JSON output, and server setup.</p>
                        </div>
                    </div>
                `;

                document.getElementById('blogCount').textContent = '0 blogs available';
            }
        }

        document.getElementById('dateFilter').addEventListener('change', filterBlogsByDate);

        document.getElementById('clearFilter').addEventListener('click', function () {
            document.getElementById('dateFilter').value = '';
            filterBlogsByDate();
        });

        loadBlogs();
    </script>
