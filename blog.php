        function normalizeDateString(dateStr) {
            if (!dateStr) return '';
            const match = String(dateStr).match(/^(\d{4})-(\d{2})-(\d{2})$/);
            return match ? `${match[1]}-${match[2]}-${match[3]}` : '';
        }

        function formatDate(dateString) {
            if (!dateString) return 'Unknown Date';

            const parts = dateString.split('-');
            if (parts.length !== 3) return dateString;

            const year = parseInt(parts[0], 10);
            const month = parseInt(parts[1], 10) - 1;
            const day = parseInt(parts[2], 10);

            const safeDate = new Date(year, month, day);
            if (isNaN(safeDate.getTime())) return dateString;

            return safeDate.toLocaleDateString('en-IN', {
                day: '2-digit',
                month: 'short',
                year: 'numeric'
            });
        }

        function generateDescription(title) {
            return `Read this blog to learn more about ${title.toLowerCase()}. Open the full article for detailed guidance and complete information.`;
