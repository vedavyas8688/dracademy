<script>
function eduSwitchTab(sectionIndex, tabIndex){
  const section = document.querySelectorAll('.edu-section')[sectionIndex];
  const tabs = section.querySelectorAll('.edu-tab');
  const panels = section.querySelectorAll('.edu-tab-panel');

  tabs.forEach((t,i)=>t.classList.toggle('edu-active', i===tabIndex));
  panels.forEach((p,i)=>p.classList.toggle('edu-active', i===tabIndex));
}

/* -------- Lightbox -------- */
const lightbox = document.getElementById('edu-lightbox');
const lightboxImg = lightbox.querySelector('img');
const btnClose = document.getElementById('edu-lightbox-close');
const btnPrev = document.getElementById('edu-lightbox-prev');
const btnNext = document.getElementById('edu-lightbox-next');

let eduImages = [];
let eduIndex = 0;

function refreshEduImages(){
  eduImages = Array.from(document.querySelectorAll('.edu-img-link img'));
}

document.addEventListener('click', (e)=>{
  const link = e.target.closest('.edu-img-link');
  if(!link) return;

  e.preventDefault();
  refreshEduImages();

  const img = link.querySelector('img');
  eduIndex = eduImages.indexOf(img);
  openEduLightbox(img.src);
});

function openEduLightbox(src){
  lightbox.style.display = 'flex';
  lightboxImg.src = src;
}

function closeEduLightbox(){
  lightbox.style.display = 'none';
  lightboxImg.src = '';
}

function showEduNext(step){
  if(!eduImages.length) return;
  eduIndex = (eduIndex + step + eduImages.length) % eduImages.length;
  lightboxImg.src = eduImages[eduIndex].src;
}

btnClose.onclick = closeEduLightbox;
btnPrev.onclick = ()=>showEduNext(-1);
btnNext.onclick = ()=>showEduNext(1);

lightbox.addEventListener('click', (e)=>{
  if(e.target === lightbox) closeEduLightbox();
});

document.addEventListener('keydown', (e)=>{
  if(lightbox.style.display !== 'flex') return;
  if(e.key === 'Escape') closeEduLightbox();
  if(e.key === 'ArrowLeft') showEduNext(-1);
  if(e.key === 'ArrowRight') showEduNext(1);
});
</script>


